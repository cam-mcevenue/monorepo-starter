import { describe, expect, it } from "@effect/vitest";
import * as path from "node:path";
import { Effect, Schema } from "effect";
import { type JsonObject, Manifest } from "@repo/cli/internal/manifest";
import { NpmScope, PackageName, RepoPath } from "@repo/cli/Model";
import {
  type Member,
  type Plan,
  planCreate,
  planMakePublic,
  planRemove,
  planSync,
  type Snapshot,
  type Sources,
  type Template,
} from "@repo/cli/Plan";

/** A member whose decoded view matches its JSON, as loading would build it. */
const member = (
  dir: string,
  kind: Member["kind"],
  json: JsonObject,
  buildConfig: string | undefined,
): Member => ({
  dir: RepoPath.make(dir),
  kind,
  json,
  manifest: Schema.decodeSync(Manifest)(json),
  buildConfig,
});

const buildConfigFragment = `{
  "extends": "./tsconfig.json",
  "include": ["src"],
  // generated by pkg sync
  "references": []
}
`;

const snapshot = (...members: ReadonlyArray<Member>): Snapshot => ({
  members: [
    member(
      "",
      "root",
      { name: "monorepo", private: true, monorepoSettings: { npmScope: "@acme" } },
      undefined,
    ),
    ...members,
  ],
  fragments: {
    buildConfig: buildConfigFragment,
    manifest: {
      files: ["src/**/*.ts", "dist/**/*.js"],
      scripts: { build: "tsrs -b tsconfig.build.json" },
      publishConfig: { access: "public" },
    },
  },
});

const publicPackage = (dir: string, json: JsonObject = {}): Member =>
  member(
    dir,
    "package",
    { name: `@acme/${path.basename(dir)}`, version: "0.0.0", ...json },
    buildConfigFragment,
  );

const writes = (snap: Snapshot) =>
  planSync(snap, path).steps.flatMap((step) => (step._tag === "Write" ? [step] : []));

const editedManifest = (snap: Snapshot, dir: string) => {
  const edit = writes(snap).find((e) => e.path === `${dir}/package.json`);
  return edit === undefined ? undefined : JSON.parse(edit.contents);
};

describe("planSync", () => {
  it("derives publishConfig.exports from exports, mapping src .ts to dist .js", () => {
    const snap = snapshot(
      publicPackage("packages/foo", {
        exports: {
          "./package.json": "./package.json",
          ".": "./src/index.ts",
          "./*": "./src/*.ts",
          "./internal/*": null,
        },
      }),
    );
    expect(editedManifest(snap, "packages/foo")?.publishConfig.exports).toEqual({
      "./package.json": "./package.json",
      ".": "./dist/index.js",
      "./*": "./dist/*.js",
      "./internal/*": null,
    });
  });

  it("adds a missing ./package.json export, first, to both maps", () => {
    const snap = snapshot(publicPackage("packages/foo", { exports: { ".": "./src/index.ts" } }));
    const manifest = editedManifest(snap, "packages/foo");
    expect(Object.keys(manifest?.exports)).toEqual(["./package.json", "."]);
    expect(Object.keys(manifest?.publishConfig.exports)).toEqual(["./package.json", "."]);
  });

  it("merges the manifest fragment: fragment values win, files keeps package extras", () => {
    const snap = snapshot(
      publicPackage("packages/foo", {
        files: ["AGENTS.md", "dist/**/*.js"],
        scripts: { build: "echo hand-edited", test: "vitest" },
      }),
    );
    const manifest = editedManifest(snap, "packages/foo");
    expect(manifest?.scripts).toEqual({ build: "tsrs -b tsconfig.build.json", test: "vitest" });
    expect(manifest?.files).toEqual(["AGENTS.md", "dist/**/*.js", "src/**/*.ts"]);
    expect(manifest?.publishConfig.access).toBe("public");
  });

  it("reports an out-of-date manifest as fixable, then nothing once synced", () => {
    const stale = snapshot(publicPackage("packages/foo", { exports: { ".": "./src/index.ts" } }));
    expect(planSync(stale, path).findings).toEqual([
      { path: "packages/foo/package.json", problem: "package.json is out of sync", fixable: true },
    ]);

    const synced = snapshot(publicPackage("packages/foo", editedManifest(stale, "packages/foo")));
    expect(planSync(synced, path)).toEqual({ steps: [], findings: [] });
  });

  it("ignores key order, since the formatter sorts package.json", () => {
    const stale = snapshot(publicPackage("packages/foo", { exports: { ".": "./src/index.ts" } }));
    const synced = editedManifest(stale, "packages/foo");
    const reversed = (value: unknown): unknown =>
      value !== null && typeof value === "object" && !Array.isArray(value)
        ? Object.fromEntries(
            Object.entries(value)
              .reverse()
              .map(([k, v]) => [k, reversed(v)]),
          )
        : value;
    const shuffled = snapshot(publicPackage("packages/foo", reversed(synced) as JsonObject));
    expect(planSync(shuffled, path)).toEqual({ steps: [], findings: [] });
  });

  it("references the build config of each workspace dep and peer dep, sorted, never dev deps", () => {
    const snap = snapshot(
      publicPackage("packages/foo", {
        dependencies: { "@acme/zed": "workspace:*", effect: "catalog:effect" },
        peerDependencies: { "@acme/bar": "workspace:*" },
        devDependencies: { "@acme/dev-only": "workspace:*" },
      }),
      publicPackage("packages/zed"),
      publicPackage("apps/bar"),
      publicPackage("packages/dev-only"),
    );
    const edit = writes(snap).find((e) => e.path === "packages/foo/tsconfig.build.json");
    expect(edit?.contents).toBe(`{
  "extends": "./tsconfig.json",
  "include": ["src"],
  // generated by pkg sync
  "references": [
    { "path": "../../apps/bar/tsconfig.build.json" },
    { "path": "../zed/tsconfig.build.json" }
  ]
}
`);
  });

  it("creates a missing build config from the fragment, even with nothing to reference", () => {
    const snap = snapshot({ ...publicPackage("packages/foo"), buildConfig: undefined });
    const plan = planSync(snap, path);
    expect(writes(snap)).toContainEqual({
      _tag: "Write",
      path: "packages/foo/tsconfig.build.json",
      contents: buildConfigFragment,
    });
    expect(plan.findings).toContainEqual({
      path: "packages/foo/tsconfig.build.json",
      problem: "tsconfig.build.json is missing",
      fixable: true,
    });
  });

  const privatePackage = (dir: string, json: JsonObject = {}, buildConfig?: string): Member =>
    member(
      dir,
      "package",
      { name: `@repo/${path.basename(dir)}`, private: true, ...json },
      buildConfig,
    );

  it("flags a public package depending on a private one, and references only public deps", () => {
    const snap = snapshot(
      publicPackage("packages/foo", { dependencies: { "@repo/secret": "workspace:*" } }),
      privatePackage("packages/secret"),
    );
    const plan = planSync(snap, path);
    expect(plan.findings).toContainEqual({
      path: "packages/foo/package.json",
      problem: "depends on private workspace package @repo/secret",
      fixable: false,
    });
    expect(writes(snap).map((e) => e.path)).not.toContain("packages/foo/tsconfig.build.json");
  });

  it("flags build leftovers on a private package without touching it", () => {
    const snap = snapshot(
      privatePackage("packages/old", { publishConfig: { access: "public" } }, buildConfigFragment),
    );
    expect(planSync(snap, path)).toEqual({
      steps: [],
      findings: [
        {
          path: "packages/old/tsconfig.build.json",
          problem: "private package has a build config; delete it or make the package public",
          fixable: false,
        },
        {
          path: "packages/old/package.json",
          problem: "private package has publishConfig; delete it or make the package public",
          fixable: false,
        },
      ],
    });
  });

  it("flags a public package named outside the scope, as a fix to make by hand", () => {
    const stray = publicPackage("packages/foo", { name: "@other/foo" });
    const synced = publicPackage("packages/foo", editedManifest(snapshot(stray), "packages/foo"));
    expect(planSync(snapshot(synced), path).findings).toEqual([
      {
        path: "packages/foo/package.json",
        problem: "public package @other/foo is outside the repo's npm scope @acme",
        fixable: false,
      },
    ]);
  });

  it("asks for monorepoSettings.npmScope only once a public package exists", () => {
    const unscoped = (...members: ReadonlyArray<Member>): Snapshot => {
      const base = snapshot(...members);
      return {
        ...base,
        members: base.members.map((m) =>
          m.kind === "root"
            ? member("", "root", { name: "monorepo", private: true }, undefined)
            : m,
        ),
      };
    };
    expect(planSync(unscoped(privatePackage("packages/a")), path).findings).toEqual([]);

    const synced = publicPackage(
      "packages/foo",
      editedManifest(snapshot(publicPackage("packages/foo")), "packages/foo"),
    );
    expect(planSync(unscoped(synced), path).findings).toEqual([
      {
        path: "package.json",
        problem: 'public packages exist but "monorepoSettings": { "npmScope" } is not set',
        fixable: false,
      },
    ]);
    expect(planSync(snapshot(synced), path).findings).toEqual([]);
  });
});

/**
 * A whole workspace in memory, as both planners' inputs: every `package.json`
 * becomes a member, and every file is a source a rename can read.
 */
const workspaceOf = (
  files: Record<string, JsonObject | string>,
  root: JsonObject = { name: "monorepo", private: true, monorepoSettings: { npmScope: "@acme" } },
) => {
  const all: Record<string, JsonObject | string> = { "package.json": root, ...files };
  const text = (contents: JsonObject | string) =>
    typeof contents === "string" ? contents : `${JSON.stringify(contents, null, 2)}\n`;
  const sources: Sources = new Map(
    Object.entries(all).map(([file, contents]) => [RepoPath.make(file), text(contents)]),
  );
  const members = Object.entries(all).flatMap(([file, contents]) =>
    path.basename(file) === "package.json" && typeof contents !== "string"
      ? [
          member(
            path.dirname(file) === "." ? "" : path.dirname(file),
            path.dirname(file) === "." ? "root" : "package",
            contents,
            undefined,
          ),
        ]
      : [],
  );
  const snap: Snapshot = { members, fragments: snapshot().fragments };
  return { snapshot: snap, sources };
};

const name = (value: string) => PackageName.make(value);

/** The text a plan writes to `file`, parsed when it is JSON. */
const written = (plan: Plan, file: string) => {
  const step = plan.steps.find((s) => s._tag === "Write" && s.path === file);
  return step?._tag === "Write" ? step.contents : undefined;
};
const writtenJson = (plan: Plan, file: string) => {
  const contents = written(plan, file);
  return contents === undefined ? undefined : JSON.parse(contents);
};

describe("planMakePublic", () => {
  it.effect("renames into the scope across sources and manifests, drops private, and syncs", () =>
    Effect.gen(function* () {
      const { snapshot: snap, sources } = workspaceOf({
        "packages/foo/package.json": { name: "@repo/foo", private: true },
        "packages/foo/test/index.test.ts": 'import { x } from "@repo/foo";\n',
        "packages/foo-extra/package.json": { name: "@repo/foo-extra", private: true },
        "packages/app/package.json": {
          name: "@repo/app",
          private: true,
          dependencies: { "@repo/foo": "workspace:*", "@repo/foo-extra": "workspace:*" },
        },
        "packages/app/src/main.ts": 'import "@repo/foo/Thing";\nimport "@repo/foo-extra";\n',
      });

      const plan = yield* planMakePublic(snap, sources, name("foo"), path);

      expect(plan).toMatchObject({ from: "@repo/foo", to: "@acme/foo" });
      const manifest = writtenJson(plan, "packages/foo/package.json");
      expect(manifest.name).toBe("@acme/foo");
      expect(manifest.private).toBeUndefined();
      expect(manifest.publishConfig.access).toBe("public");
      expect(written(plan, "packages/foo/tsconfig.build.json")).toBeDefined();
      expect(written(plan, "packages/foo/test/index.test.ts")).toContain('from "@acme/foo"');
      expect(Object.keys(writtenJson(plan, "packages/app/package.json").dependencies)).toEqual([
        "@acme/foo",
        "@repo/foo-extra",
      ]);
      expect(written(plan, "packages/app/src/main.ts")).toBe(
        'import "@acme/foo/Thing";\nimport "@repo/foo-extra";\n',
      );
      // One write per file, even where the rename and the sync both touched it.
      const paths = plan.steps.map((step) => (step._tag === "Write" ? step.path : ""));
      expect(new Set(paths).size).toBe(paths.length);
    }),
  );

  it.effect("refuses without a scope, already public, or with private deps listed", () =>
    Effect.gen(function* () {
      const unscoped = workspaceOf(
        { "packages/foo/package.json": { name: "@repo/foo", private: true } },
        { name: "monorepo", private: true },
      );
      const noScope = yield* Effect.flip(
        planMakePublic(unscoped.snapshot, unscoped.sources, name("foo"), path),
      );
      expect(noScope._tag).toBe("ScopeUnset");

      const published = workspaceOf({ "packages/foo/package.json": { name: "@acme/foo" } });
      const already = yield* Effect.flip(
        planMakePublic(published.snapshot, published.sources, name("foo"), path),
      );
      expect(already).toMatchObject({ _tag: "AlreadyPublic", dir: "packages/foo" });

      const withPrivateDeps = workspaceOf({
        "packages/foo/package.json": {
          name: "@repo/foo",
          private: true,
          dependencies: { "@repo/a": "workspace:*" },
          peerDependencies: { "@repo/b": "workspace:*" },
        },
        "packages/a/package.json": { name: "@repo/a", private: true },
        "packages/b/package.json": { name: "@repo/b", private: true },
      });
      const blocked = yield* Effect.flip(
        planMakePublic(withPrivateDeps.snapshot, withPrivateDeps.sources, name("foo"), path),
      );
      expect(blocked).toMatchObject({
        _tag: "DependsOnPrivate",
        dependencies: ["@repo/a", "@repo/b"],
      });
    }),
  );
});

describe("planCreate", () => {
  const template: Template = {
    name: "pkg-lib",
    dir: "/repo/packages/cli/templates/pkg-lib",
    files: new Map([
      ["package.json", '{\n  "name": "@repo/template",\n  "private": true\n}\n'],
      ["tsconfig.json", '{\n  // keep me\n  "extends": "../../../../tsconfig.base.json"\n}\n'],
      ["test/index.test.ts", 'import { greet } from "@repo/template";\n'],
      ["src/index.ts", "export const greet = 1;\n"],
    ]),
    pruned: ["node_modules"],
  };

  it.effect("private: copies, prunes, then repoints the name and the extends", () =>
    Effect.gen(function* () {
      const { snapshot: snap } = workspaceOf({});
      const plan = yield* planCreate(snap, template, name("widget"), "private", "/repo", path);

      expect(plan).toMatchObject({ packageName: "@repo/widget", packagePath: "packages/widget" });
      expect(plan.steps.slice(0, 2)).toEqual([
        { _tag: "Copy", from: template.dir, to: "packages/widget" },
        { _tag: "Remove", path: "packages/widget/node_modules" },
      ]);
      expect(writtenJson(plan, "packages/widget/package.json").name).toBe("@repo/widget");
      expect(written(plan, "packages/widget/tsconfig.json")).toBe(
        '{\n  // keep me\n  "extends": "../../tsconfig.base.json"\n}\n',
      );
      expect(written(plan, "packages/widget/test/index.test.ts")).toContain('"@repo/widget"');
      // Unchanged by the copy, so not rewritten.
      expect(written(plan, "packages/widget/src/index.ts")).toBeUndefined();
      expect(written(plan, "packages/widget/tsconfig.build.json")).toBeUndefined();
    }),
  );

  it.effect("public: names the copy into the scope and gives it a build config", () =>
    Effect.gen(function* () {
      const { snapshot: snap } = workspaceOf({});
      const plan = yield* planCreate(snap, template, name("widget"), "public", "/repo", path);

      expect(plan.packageName).toBe("@acme/widget");
      const manifest = writtenJson(plan, "packages/widget/package.json");
      expect(manifest.private).toBeUndefined();
      expect(manifest.publishConfig.access).toBe("public");
      expect(written(plan, "packages/widget/tsconfig.build.json")).toBeDefined();
      expect(written(plan, "packages/widget/test/index.test.ts")).toContain('"@acme/widget"');
    }),
  );

  it.effect("refuses a taken directory, and a public package without a scope", () =>
    Effect.gen(function* () {
      const taken = workspaceOf({ "packages/widget/package.json": { name: "@repo/widget" } });
      const exists = yield* Effect.flip(
        planCreate(taken.snapshot, template, name("widget"), "private", "/repo", path),
      );
      expect(exists._tag).toBe("AlreadyExists");

      const unscoped = workspaceOf({}, { name: "monorepo", private: true });
      const noScope = yield* Effect.flip(
        planCreate(unscoped.snapshot, template, name("widget"), "public", "/repo", path),
      );
      expect(noScope._tag).toBe("ScopeUnset");
    }),
  );
});

describe("planRemove", () => {
  it.effect("refuses while any member depends on it, listing each field", () =>
    Effect.gen(function* () {
      const { snapshot: snap } = workspaceOf({
        "packages/foo/package.json": { name: "@acme/foo" },
        "packages/app/package.json": {
          name: "@repo/app",
          private: true,
          devDependencies: { "@acme/foo": "workspace:*" },
        },
        "packages/lib/package.json": {
          name: "@acme/lib",
          peerDependencies: { "@acme/foo": "workspace:*" },
        },
      });
      const refused = yield* Effect.flip(planRemove(snap, name("foo"), path));
      expect(refused).toMatchObject({
        _tag: "HasDependents",
        packageName: "@acme/foo",
        dependents: [
          "packages/app/package.json (devDependencies)",
          "packages/lib/package.json (peerDependencies)",
        ],
      });

      const plan = yield* planRemove(snap, name("app"), path);
      expect(plan).toMatchObject({ packageName: "@repo/app", wasPublic: false });
      expect(plan.steps[0]).toEqual({ _tag: "Remove", path: "packages/app" });
    }),
  );

  it.effect("refuses the CLI itself, and a directory that is not a member", () =>
    Effect.gen(function* () {
      const { snapshot: snap } = workspaceOf({});
      expect((yield* Effect.flip(planRemove(snap, name("cli"), path)))._tag).toBe(
        "ProtectedPackage",
      );
      expect((yield* Effect.flip(planRemove(snap, name("ghost"), path)))._tag).toBe(
        "PackageNotFound",
      );
    }),
  );
});

describe("a scope given for a repo that has none", () => {
  const unscopedRoot: JsonObject = { name: "monorepo", private: true, scripts: { x: "@repo/foo" } };
  const scope = NpmScope.make("@given");

  it.effect("make-public records it in the root manifest, which the rename then keeps", () =>
    Effect.gen(function* () {
      const { snapshot: snap, sources } = workspaceOf(
        { "packages/foo/package.json": { name: "@repo/foo", private: true } },
        unscopedRoot,
      );
      const plan = yield* planMakePublic(snap, sources, name("foo"), path, scope);
      expect(plan.to).toBe("@given/foo");
      // The root script names the package, so the rename rewrote the root too.
      expect(writtenJson(plan, "package.json")).toEqual({
        name: "monorepo",
        private: true,
        scripts: { x: "@given/foo" },
        monorepoSettings: { npmScope: "@given" },
      });
    }),
  );

  it.effect("add names the package into it, and records it", () =>
    Effect.gen(function* () {
      const { snapshot: snap } = workspaceOf({}, { name: "monorepo", private: true });
      const template: Template = {
        name: "pkg-lib",
        dir: "/repo/packages/cli/templates/pkg-lib",
        files: new Map([["package.json", '{ "name": "@repo/template", "private": true }']]),
        pruned: [],
      };
      const plan = yield* planCreate(
        snap,
        template,
        name("widget"),
        "public",
        "/repo",
        path,
        scope,
      );
      expect(plan.packageName).toBe("@given/widget");
      expect(writtenJson(plan, "package.json").monorepoSettings).toEqual({ npmScope: "@given" });
    }),
  );

  it.effect("refuses one that differs from the repo's own", () =>
    Effect.gen(function* () {
      const { snapshot: snap, sources } = workspaceOf({
        "packages/foo/package.json": { name: "@repo/foo", private: true },
      });
      const error = yield* Effect.flip(planMakePublic(snap, sources, name("foo"), path, scope));
      expect(error).toMatchObject({ _tag: "ScopeMismatch", configured: "@acme", given: "@given" });
    }),
  );
});
